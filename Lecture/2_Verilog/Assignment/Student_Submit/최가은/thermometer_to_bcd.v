module thermometer_to_bcd(
    output reg[7:0] bcd,
    input [15:0] thermometer
    );
    always @(*)begin
        if (~thermometer)
            bcd=0;
        case (thermometer)
            16'b0000_0000_0000_0001:bcd<=8'b1;
            16'b0000_0000_0000_0011:bcd<=8'b10;
            16'b0000_0000_0000_0111:bcd<=8'b11;
            16'b0000_0000_0000_1111:bcd<=8'b100;
            16'b0000_0000_0001_1111:bcd<=8'b101;
            16'b0000_0000_0011_1111:bcd<=8'b110;
            16'b0000_0000_0111_1111:bcd<=8'b111;
            16'b0000_0000_1111_1111:bcd<=8'b1000;
            16'b0000_0001_1111_1111:bcd<=8'b1001;
            16'b0000_0011_1111_1111:bcd<=8'b10000;
            16'b0000_0111_1111_1111:bcd<=8'b10001;
            16'b0000_1111_1111_1111:bcd<=8'b10010;
            16'b0001_1111_1111_1111:bcd<=8'b10011;
            16'b0011_1111_1111_1111:bcd<=8'b10100;
            16'b0111_1111_1111_1111:bcd<=8'b10101;
            16'b1111_1111_1111_1111:bcd<=8'b10110;
        endcase
        end
            
            
        
endmodule
